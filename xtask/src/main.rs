//! Explicit, offline-capable frontend generation; no build script downloads tools.
use std::{
    env,
    error::Error,
    fs,
    path::{Path, PathBuf},
    process::{Command, ExitCode},
    time::{SystemTime, UNIX_EPOCH},
};
type Result<T> = std::result::Result<T, Box<dyn Error>>;
const BINDGEN_VERSION: &str = "wasm-bindgen 0.2.129";
const TARGET: &str = "wasm32-unknown-unknown";
const START: &str = r#"// Generated by cargo xtask build-web. Application code lives in crates/ui.
try {
  const { default: init } = await import('./business_apps_ui.js');
  await init();
}
catch (error) {
  const status = document.getElementById('boot-status');
  if (status) status.textContent = '画面を起動できませんでした。ページを再読み込みしてください。';
  console.error('Rust UI startup failed', error);
}
"#;
fn main() -> ExitCode {
    match task() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("{error}");
            ExitCode::FAILURE
        }
    }
}
fn task() -> Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or("Missing workspace root")?;
    let args: Vec<_> = env::args().skip(1).collect();
    let operation = args.first().map(String::as_str).unwrap_or("help");
    if args.len() > 1 {
        return Err("Use cargo xtask build-web, dev, or build (configure BIZAPP_BIND/BIZAPP_DB through the environment).".into());
    }
    match operation {
        "build-web" => build_web(root),
        "dev" => {
            build_web(root)?;
            run(Command::new(cargo()).current_dir(root).args([
                "run",
                "--locked",
                "-p",
                "business-apps-server",
            ]))
        }
        "build" => {
            build_web(root)?;
            run(Command::new(cargo()).current_dir(root).args([
                "build",
                "--release",
                "--locked",
                "-p",
                "business-apps-server",
            ]))
        }
        "help" | "--help" | "-h" => {
            println!(
                "cargo xtask build-web  Generate Rust UI WebAssembly and browser glue\ncargo xtask dev        Build UI, then run the local server\ncargo xtask build      Build UI and the release server binary"
            );
            Ok(())
        }
        _ => Err(format!("Unknown task {operation:?}. Use cargo xtask --help.").into()),
    }
}
fn cargo() -> std::ffi::OsString {
    env::var_os("CARGO").unwrap_or_else(|| "cargo".into())
}
fn run(command: &mut Command) -> Result<()> {
    let status = command.status()?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("Build command exited with {status}; no later build step was run.").into())
    }
}
struct Staging(PathBuf);
impl Drop for Staging {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}
fn build_web(root: &Path) -> Result<()> {
    let bindgen = env::var_os("BIZAPP_WASM_BINDGEN").unwrap_or_else(|| "wasm-bindgen".into());
    let output = Command::new(&bindgen).arg("--version").output().map_err(|error| format!("wasm-bindgen CLI is unavailable ({error}). Install it with: cargo install wasm-bindgen-cli --version 0.2.129 --locked (or set BIZAPP_WASM_BINDGEN)."))?;
    if !output.status.success() || String::from_utf8_lossy(&output.stdout).trim() != BINDGEN_VERSION
    {
        return Err(format!("Expected {BINDGEN_VERSION}. Install the pinned CLI before building; mismatched glue is refused.").into());
    }
    run(Command::new(cargo()).current_dir(root).args([
        "build",
        "--locked",
        "--release",
        "-p",
        "business-apps-ui",
        "--target",
        TARGET,
    ]))?;
    // Let Cargo resolve config files and both target-directory environment variables.
    // Guessing root/target could silently package an older module after a valid build.
    let metadata = Command::new(cargo())
        .current_dir(root)
        .args(["metadata", "--locked", "--no-deps", "--format-version", "1"])
        .output()?;
    if !metadata.status.success() {
        return Err(format!(
            "Cargo metadata failed: {}",
            String::from_utf8_lossy(&metadata.stderr)
        )
        .into());
    }
    let metadata: serde_json::Value = serde_json::from_slice(&metadata.stdout)?;
    let target = PathBuf::from(
        metadata["target_directory"]
            .as_str()
            .ok_or("Cargo metadata omitted target_directory")?,
    );
    let wasm = target.join(TARGET).join("release/business_apps_ui.wasm");
    let stamp = SystemTime::now().duration_since(UNIX_EPOCH)?.as_nanos();
    let staging = Staging(
        root.join(".artifacts")
            .join(format!("ui-build-{}-{stamp}", std::process::id())),
    );
    fs::create_dir_all(&staging.0)?;
    run(Command::new(bindgen)
        .current_dir(root)
        .arg(&wasm)
        .args([
            "--target",
            "web",
            "--no-typescript",
            "--out-name",
            "business_apps_ui",
            "--out-dir",
        ])
        .arg(&staging.0))?;
    fs::write(staging.0.join("start.js"), START)?;
    let destination = root.join("web/pkg");
    fs::create_dir_all(&destination)?;
    for file in [
        "business_apps_ui.js",
        "business_apps_ui_bg.wasm",
        "start.js",
    ] {
        let bytes = fs::read(staging.0.join(file))?;
        if file.ends_with(".wasm") && !bytes.starts_with(b"\0asm\x01\0\0\0") {
            return Err("Generated artifact is not a WebAssembly module".into());
        }
        let path = destination.join(file);
        if fs::read(&path).ok().as_deref() != Some(bytes.as_slice()) {
            fs::write(path, &bytes)?;
        }
        println!("Generated {file}: {} bytes", bytes.len());
    }
    Ok(())
}
